CREATE TABLE IF NOT EXISTS learners (name TEXT PRIMARY KEY, display_name TEXT NOT NULL, updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS events (name TEXT NOT NULL, id TEXT NOT NULL, at INTEGER NOT NULL, event TEXT NOT NULL, PRIMARY KEY(name,id));
CREATE INDEX IF NOT EXISTS events_learner_time ON events(name,at);
CREATE TABLE IF NOT EXISTS subscriptions (endpoint TEXT PRIMARY KEY, name TEXT NOT NULL, timezone TEXT NOT NULL, hour INTEGER NOT NULL, minute INTEGER NOT NULL, last_day TEXT);
CREATE TABLE IF NOT EXISTS config (key TEXT PRIMARY KEY, value TEXT NOT NULL);
